#ifndef HINGESCRIBE_REGISTERS_H
#define HINGESCRIBE_REGISTERS_H
#include <stdint.h>
#define REG32(address) (*(volatile uint32_t *)(uintptr_t)(address))
#define NRF_CLOCK_BASE 0x40000000UL
#define NRF_RADIO_BASE 0x40001000UL
#define NRF_TWIM0_BASE 0x40003000UL
#define NRF_SAADC_BASE 0x40007000UL
#define NRF_TIMER1_BASE 0x40009000UL
#define NRF_RTC1_BASE 0x40011000UL
#define NRF_WDT_BASE 0x40010000UL
#define NRF_NVMC_BASE 0x4001E000UL
#define NRF_GPIO_BASE 0x50000000UL
#define TASK(base, offset) REG32((base) + (offset))
#define EVENT(base, offset) REG32((base) + (offset))
#define NRF_CLOCK_TASKS_HFCLKSTART TASK(NRF_CLOCK_BASE, 0x000)
#define NRF_CLOCK_EVENTS_HFCLKSTARTED EVENT(NRF_CLOCK_BASE, 0x100)
#define NRF_GPIO_OUTSET REG32(NRF_GPIO_BASE + 0x508)
#define NRF_GPIO_OUTCLR REG32(NRF_GPIO_BASE + 0x50C)
#define NRF_GPIO_IN REG32(NRF_GPIO_BASE + 0x510)
#define NRF_GPIO_DIRSET REG32(NRF_GPIO_BASE + 0x518)
#define NRF_GPIO_PIN_CNF(pin) REG32(NRF_GPIO_BASE + 0x700 + ((pin) * 4u))
#define NRF_TWIM_TASKS_STARTRX TASK(NRF_TWIM0_BASE, 0x000)
#define NRF_TWIM_TASKS_STARTTX TASK(NRF_TWIM0_BASE, 0x008)
#define NRF_TWIM_TASKS_STOP TASK(NRF_TWIM0_BASE, 0x014)
#define NRF_TWIM_EVENTS_STOPPED EVENT(NRF_TWIM0_BASE, 0x104)
#define NRF_TWIM_EVENTS_ERROR EVENT(NRF_TWIM0_BASE, 0x124)
#define NRF_TWIM_ENABLE REG32(NRF_TWIM0_BASE + 0x500)
#define NRF_TWIM_PSEL_SCL REG32(NRF_TWIM0_BASE + 0x508)
#define NRF_TWIM_PSEL_SDA REG32(NRF_TWIM0_BASE + 0x50C)
#define NRF_TWIM_FREQUENCY REG32(NRF_TWIM0_BASE + 0x524)
#define NRF_TWIM_ADDRESS REG32(NRF_TWIM0_BASE + 0x588)
#define NRF_WDT_TASKS_START TASK(NRF_WDT_BASE, 0x000)
#define NRF_WDT_CRV REG32(NRF_WDT_BASE + 0x504)
#define NRF_WDT_RREN REG32(NRF_WDT_BASE + 0x508)
#define NRF_WDT_RR0 REG32(NRF_WDT_BASE + 0x600)
#define NRF_NVMC_READY REG32(NRF_NVMC_BASE + 0x400)
#define NRF_NVMC_CONFIG REG32(NRF_NVMC_BASE + 0x504)
#define BIT(n) (1UL << (n))
#endif
